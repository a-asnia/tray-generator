// ── Съёмная визитница ──
// Карман для визиток, который цепляется крюками за пару сквозных окон у
// верха внешней стенки (галка «Отверстия под визитницу» в редакторе
// стенки). Сам карман — отдельная печатная деталь: спинка прижимается к
// наружной плоскости стенки, крюки проходят сквозь окна и свисают по
// внутренней стороне — визитница снимается движением вверх.
//
// Печатается лёжа на боку (в STL так и лежит): каждый слой — профиль
// кармана, поддержки не нужны, под крюками лишь короткое нависание.

import { boxSolid } from "../geometry/solids.js";

// Окна в стенке: hw×hh, пара с шагом sp, верх окна на top ниже кромки.
// Стенка должна быть не ниже minH (иначе окна некуда резать) и не уже
// minW; back/depth/frontH — габариты самого кармана.
// wallH — высота стенки, при которой навешенный карман не упирается в
// стол: окна у кромки, а спинка висит на (back − плечо) ниже них.
export const CARDH = { hw: 12, hh: 6, sp: 40, top: 4, minW: 60, minH: 22, back: 55, depth: 14, frontH: 30 };
CARDH.wallH = Math.ceil(CARDH.top + CARDH.hh + CARDH.back - (CARDH.hh - 2.5) + 2);

// Съёмный карман: спинка + дно + передний борт + два крюка.
// wallOut контейнера задаёт длину плеча крюка (сквозь стенку).
export function cardHolderSolids(c) {
  const wallOut = c && Number.isFinite(c.wallOut) ? c.wallOut : 2.9;
  const W = 70, Hb = CARDH.back, T = 2.4;         // спинка: ширина, высота, толщина
  const depth = CARDH.depth, frontH = CARDH.frontH; // карман: глубина и высота борта
  const hookW = CARDH.hw - 2;       // крюк уже окна на зазор по 1 мм
  const armT = CARDH.hh - 2.5;      // плечо ниже окна — люфт для навешивания
  const armL = wallOut + 0.6;       // плечо проходит стенку насквозь
  const lipDrop = 10;               // носик свисает за внутренней стороной
  const solids = [];
  const add = (x0, x1, y0, y1, z0, z1) =>
    solids.push(boxSolid((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2, x1 - x0, y1 - y0, z1 - z0, "card"));
  // натуральная ориентация: x — ширина, y — высота, z — глубина (карман в −z)
  add(-W / 2, W / 2, 0, Hb, 0, T);                    // спинка
  add(-W / 2, W / 2, 0, T, -depth, 0);                // дно кармана
  add(-W / 2, W / 2, 0, frontH, -depth, -depth + T);  // передний борт
  for (const s of [-1, 1]) {
    const x0 = (s * CARDH.sp) / 2 - hookW / 2, x1 = (s * CARDH.sp) / 2 + hookW / 2;
    add(x0, x1, Hb - armT, Hb, T, T + armL);                       // плечо
    add(x0, x1, Hb - armT - lipDrop, Hb, T + armL, T + armL + T);  // носик
  }
  // повернуть на бок (вокруг Z, определитель +1 — нормали целы) и
  // поставить на стол: вертикаль печати — вдоль ширины детали
  return solids.map((b) => ({
    tag: "card",
    tris: b.tris.map((t) => t.map(([x, y, z]) => [y, W / 2 - x, z + depth])),
  }));
}
