// Вставные стенки контейнера: контейнер печатается как БАЗА (дно +
// угловые стойки + всё внутреннее) и четыре плоские СТЕНКИ, которые
// вдвигаются в стойки сверху.
//
// Стенка снаружи стоит вровень с габаритом — иначе контейнеры перестали бы
// смыкаться вплотную, а замки «ласточкин хвост» на этих стенках работать.
// Держат её угловые стойки: у стойки сквозной паз, у стенки на концах шип,
// утопленный от наружной плоскости. Наружная плоскость поэтому ровная на
// всю высоту: снизу и по углам её образует стойка, между ними — стенка.
//
//   вид сверху, угол
//   ┌─────────┬──────────────────
//   │ стойка  │▓▓▓▓ стенка ▓▓▓▓▓   ← снаружи вровень
//   │  ┌───┐  │  ┌──┐
//   │  │паз│  │  │шип
//   └──┴───┴──┴──┴────────────────
// ══════════════════════════════════════════════════════════════

export const DEF_WPARTS = {
  on: false,
  tng: 1.4,   // толщина шипа на конце стенки
  clr: 0.2,   // зазор на сторону между шипом и пазом стойки
  post: 12,   // длина угловой стойки вдоль стенки
};
export const wpartsOf = (c) => ({ ...DEF_WPARTS, ...(c && c.wparts) });

// Минимальная толщина внешней стенки: по обе стороны от паза должно
// остаться хотя бы по 0,8 мм стенки стойки, иначе стойку не напечатать.
export const wpMinWall = (w) => Math.round((w.tng + 2 * w.clr + 1.6) * 100) / 100;

// Производные размеры соединения
export function wpGeom(c) {
  const w = wpartsOf(c);
  const cw = w.tng + 2 * w.clr;                    // ширина паза в стойке
  const tOut = Math.max(0.8, (c.wallOut - cw) / 2); // от наружной плоскости до паза
  const post = Math.max(c.wallOut + 4, w.post);     // стойка длиннее толщины стенки
  return { ...w, cw, tOut, post, minWall: wpMinWall(w) };
}

// Пролёт вдоль стенки: [основное тело], [конец шипа]. dim — габарит
// контейнера вдоль этой стенки.
export function wpSpans(c, dim) {
  const g = wpGeom(c);
  const body = dim / 2 - g.post - g.clr;   // основное тело: между стойками
  const tip = dim / 2 - c.wallOut - g.clr; // шип заходит в стойку до угла
  return { body, tip, g };
}

// Готова ли геометрия: слишком тонкая стенка или слишком маленький
// контейнер соединение не выдержат
export function wpOk(c) {
  const g = wpGeom(c);
  if (c.wallOut < g.minWall - 0.001) return false;
  return Math.min(c.W, c.D) / 2 - g.post - g.clr > 4;
}

// Габариты одной детали-стенки (для подписи в UI и имени файла)
export function wpSize(c, axis) {
  const dim = axis === "x" ? c.W : c.D; // стенка вдоль X (N/S) или вдоль Z (W/E)
  const { tip } = wpSpans(c, dim);
  return {
    len: Math.round(2 * tip * 10) / 10,
    hgt: Math.round((c.H - c.floor) * 10) / 10,
    thk: c.wallOut,
  };
}

// Разложить деталь плашмя для печати: толщина становится вертикальной,
// высота стенки ложится в плоскость стола — печатается без поддержек.
// side: n/s — стенка вдоль X, w/e — вдоль Z.
export function wpFlatten(solids, side, c) {
  const along = side === "n" || side === "s";
  const outer = side === "n" ? -c.D / 2 : side === "s" ? c.D / 2 : side === "w" ? -c.W / 2 : c.W / 2;
  const sgn = side === "n" || side === "w" ? 1 : -1;
  const yBot = c.floor;
  return solids.map((b) => ({
    tag: b.tag,
    tris: b.tris.map((t) =>
      t.map(([x, y, z]) => {
        const u = along ? x : z;                       // вдоль стенки
        const v = sgn * ((along ? z : x) - outer);      // поперёк (толщина)
        return [u, v, y - yBot];
      })
    ),
  }));
}
